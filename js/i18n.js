const original = new WeakMap();
const reverse = new Map(Object.entries(EN).map(([en, ar]) => [ar, en]));
function translateNode(node, lang) {
  if (node.nodeType === Node.TEXT_NODE) {
    if (!original.has(node)) original.set(node, node.nodeValue);
    const raw = original.get(node), key = raw.trim();
    const value = lang === 'ar' ? (EN[key] || key) : (reverse.get(key) || key);
    if (value !== key || raw !== node.nodeValue) {
      const lead = raw.match(/^\s*/)?.[0] || '', tail = raw.match(/\s*$/)?.[0] || '';
      node.nodeValue = lead + value + tail;
    }
  } else if (node.nodeType === Node.ELEMENT_NODE) {
    for (const attr of ['placeholder','title','aria-label']) {
      if (node.hasAttribute(attr)) {
        const key = `attr:${attr}`;
        if (!original.has(node[key])) node[key] = node.getAttribute(attr);
        const raw = node[key], k = raw.trim();
        node.setAttribute(attr, lang === 'ar' ? (EN[k] || k) : (reverse.get(k) || k));
      }
    }
    node.childNodes.forEach(n => translateNode(n, lang));
  }
}
export function applyLanguage(lang = S.prefs.language || 'en') {
  const ar = lang === 'ar';
  document.documentElement.lang = ar ? 'ar' : 'en';
  document.documentElement.dir = ar ? 'rtl' : 'ltr';
  document.documentElement.dataset.lang = ar ? 'ar' : 'en';
  translateNode(document.body, ar ? 'ar' : 'en');
}
export function initLanguage() {
  applyLanguage();
  const observer = new MutationObserver(records => {
    for (const r of records) {
      if (r.type === 'childList') r.addedNodes.forEach(n => translateNode(n, S.prefs.language || 'en'));
      else if (r.type === 'characterData') translateNode(r.target, S.prefs.language || 'en');
    }
  });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
}
